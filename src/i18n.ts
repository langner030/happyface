export function getLanguage(): Language {
  if (typeof window !== "undefined") {
    const queryLang = new URLSearchParams(window.location.search).get("lang");
    if (queryLang === "de" || queryLang === "en") {
      localStorage.setItem(STORAGE_KEY, queryLang);
      return queryLang;
    }
    const stored = localStorage.getItem(STORAGE_KEY);
    if (stored === "de" || stored === "en") return stored;
  }
  return "en";
}

export function t(key: keyof typeof MESSAGES.en, vars?: Record<string, string | number>) {
  const lang = getLanguage();
  let value: string = MESSAGES[lang][key] ?? MESSAGES.en[key];
  if (!vars) return value;
  for (const [name, replacement] of Object.entries(vars)) {
    value = value.split(`{${name}}`).join(String(replacement));
  }
  return value;
}

export function getLocale() {
  return getLanguage() === "de" ? "de-DE" : "en-US";
}

